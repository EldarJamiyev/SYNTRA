import assert from "node:assert/strict";
import { createCache } from "../src/index.mjs";

const cache = createCache();
const objectKey = {};
assert.equal(cache.size, 0);
assert.equal(cache.get("missing"), undefined);
assert.equal(cache.has("missing"), false);
assert.equal(cache.set("name", "SYNTRA"), cache);
assert.equal(cache.get("name"), "SYNTRA");
assert.equal(cache.has("name"), true);
assert.equal(cache.set(objectKey, undefined), cache);
assert.equal(cache.has(objectKey), true);
assert.equal(cache.get(objectKey), undefined);
assert.equal(cache.size, 2);
assert.equal(cache.delete("name"), true);
assert.equal(cache.delete("name"), false);
assert.equal(cache.size, 1);
cache.clear();
assert.equal(cache.size, 0);
