"""Approved local source discovery and deterministic instruction-corpus synthesis."""
from __future__ import annotations
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
from typing import Iterable
from syntra_ai.safe_paths import resolve_corpus_root

SOURCE_SUFFIXES = frozenset({".py", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".json", ".md", ".mdx"})
SKIP_DIRECTORIES = frozenset({
    ".git", ".hg", ".svn", ".venv", "venv", "env", ".tox", "__pycache__",
    ".pytest_cache", ".mypy_cache", ".ruff_cache", ".cache", ".idea", ".vscode",
    "node_modules", "vendor", "dist", "build", "out", "target", "coverage",
    ".next", ".nuxt", ".turbo", "site-packages", "checkpoints", "artifacts",
    "logs", "benchmark-results", "corpus", "runs", "wandb", "mlruns",
})
SENSITIVE_DIRECTORY_NAMES = frozenset({
    "secrets", "credentials", "private", "private_keys", "certificates",
    "certs", ".ssh", ".aws", ".azure",
})
SENSITIVE_SUFFIXES = frozenset({
    ".pem", ".key", ".p12", ".pfx", ".p7b", ".p7c", ".jks", ".crt",
    ".cer", ".der", ".keystore", ".sqlite", ".db", ".dump", ".bak", ".log",
})
MAX_FILES = 10_000
MAX_FILE_BYTES = 512 * 1024
MAX_TOTAL_BYTES = 128 * 1024 * 1024
MAX_RECORDS = 50_000
BOILERPLATE_LINE_PATTERNS = (
    re.compile(r"^\s*!\[[^]]*\]\([^)]*(?:shields\.io|badge|travis|codecov)[^)]*\)\s*$", re.I),
    re.compile(r"^\s*<!--\s*(?:generated|auto-generated|table of contents|toc).*?-->\s*$", re.I),
    re.compile(r"^\s*\[?back to top\]?\s*$", re.I),
    re.compile(r"^\s*this readme was generated by\b.*$", re.I),
    re.compile(r"^\s*<!--\s*START OF (?:GENERATED )?CONTENT\s*-->\s*$", re.I),
    re.compile(r"^\s*<!--\s*END OF (?:GENERATED )?CONTENT\s*-->\s*$", re.I),
)
DECLARATION_PATTERNS = {
    "Python": re.compile(r"^\s*(?:async\s+)?(?:def|class)\s+([A-Za-z_][A-Za-z0-9_]*)", re.M),
    "JavaScript": re.compile(r"^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^\s*(?:export\s+)?class\s+([A-Za-z_$][\w$]*)", re.M),
    "TypeScript": re.compile(r"^\s*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^\s*(?:export\s+)?class\s+([A-Za-z_$][\w$]*)|^\s*(?:export\s+)?interface\s+([A-Za-z_$][\w$]*)|^\s*(?:export\s+)?type\s+([A-Za-z_$][\w$]*)", re.M),
}
IMPORT_PATTERN = re.compile(r"^\s*(?:import\s+.*?\s+from\s+|from\s+)(['\"]?)([A-Za-z0-9_./@-]+)\1", re.M)

@dataclass(frozen=True)
class PreparedCorpus:
    records: list[dict[str, str]]
    files: list[str]
    source_bytes: int
    sha256: str
    skipped_files: int

def _sensitive_name(name: str) -> bool:
    lowered = name.casefold()
    if lowered == ".env" or lowered.startswith(".env."):
        return True
    if lowered in {
        ".npmrc", ".pypirc", "credentials", "credentials.json", "secrets.json",
        "id_rsa", "id_ed25519", "known_hosts", "authorized_keys",
        "access_token", "refresh_token", "token.txt",
    }:
        return True
    if any(value in lowered for value in ("secret", "credential", "password", "private_key", "private-key")):
        return True
    return Path(lowered).suffix in SENSITIVE_SUFFIXES

def _is_hidden_or_sensitive(path: Path, root: Path) -> bool:
    try:
        parts = path.relative_to(root).parts
    except ValueError:
        return True
    return any(part.startswith(".") or part.casefold() in SENSITIVE_DIRECTORY_NAMES or _sensitive_name(part) for part in parts)

def normalize_source_text(text: str, suffix: str) -> str:
    """Normalize Unicode and whitespace, removing common generated Markdown noise."""
    value = text.replace("\ufeff", "").replace("\r\n", "\n").replace("\r", "\n").replace("\x00", "")
    if suffix.lower() in {".md", ".mdx"}:
        value = re.sub(r"<!--[\s\S]*?-->", "", value)
        lines = []
        in_toc = False
        for line in value.split("\n"):
            lowered = line.strip().casefold()
            if re.match(r"^#{1,6}\s+(table of contents|contents|quick navigation)\s*$", lowered):
                in_toc = True
                continue
            if in_toc:
                if re.match(r"^#{1,6}\s+", line.strip()):
                    in_toc = False
                else:
                    continue
            if any(pattern.match(line) for pattern in BOILERPLATE_LINE_PATTERNS):
                continue
            if "shields.io" in line.casefold() and line.lstrip().startswith(("![", "[![", "<a ")):
                continue
            lines.append(line.rstrip())
        value = "\n".join(lines)
    else:
        value = "\n".join(line.rstrip() for line in value.split("\n"))
    return re.sub(r"\n{3,}", "\n\n", value).strip()

def _language(path: Path) -> str:
    suffix = path.suffix.lower()
    if suffix == ".py": return "Python"
    if suffix in {".ts", ".tsx"}: return "TypeScript"
    if suffix in {".js", ".jsx", ".mjs", ".cjs"}: return "JavaScript"
    if suffix == ".json": return "JSON"
    return "Markdown"

def _split_lines(text: str, maximum: int) -> list[str]:
    chunks: list[str] = []
    current: list[str] = []
    current_size = 0
    for line in text.splitlines(keepends=True):
        if len(line) > maximum:
            if current:
                chunks.append("".join(current).strip())
                current, current_size = [], 0
            chunks.extend(line[offset:offset + maximum].strip() for offset in range(0, len(line), maximum))
            continue
        if current and current_size + len(line) > maximum:
            chunks.append("".join(current).strip())
            current, current_size = [], 0
        current.append(line)
        current_size += len(line)
    if current:
        chunks.append("".join(current).strip())
    return [chunk for chunk in chunks if len(chunk) >= 24]

def _declaration_summary(content: str, language: str) -> str:
    pattern = DECLARATION_PATTERNS.get(language)
    names: list[str] = []
    if pattern:
        for match in pattern.finditer(content):
            name = next((group for group in match.groups() if group), "")
            if name and name not in names:
                names.append(name)
            if len(names) >= 16: break
    imports: list[str] = []
    for match in IMPORT_PATTERN.finditer(content):
        value = match.group(2)
        if value and value not in imports: imports.append(value)
        if len(imports) >= 12: break
    return "\n".join((
        f"This {language} source excerpt is from a local project file.",
        "Declarations visible in this excerpt: " + (", ".join(names) if names else "no supported declaration matched.") + ".",
        "Import specifiers visible in this excerpt: " + (", ".join(imports) if imports else "no supported import matched.") + ".",
        "These notes describe visible syntax only and do not infer runtime behavior.",
    ))

def build_instruction_corpus(
    roots: Iterable[str | Path],
    *,
    max_files: int = MAX_FILES,
    max_file_bytes: int = MAX_FILE_BYTES,
    max_total_bytes: int = MAX_TOTAL_BYTES,
    chunk_chars: int = 900,
) -> PreparedCorpus:
    """Collect approved code/documentation files and synthesize grounded tasks."""
    if not 1 <= max_files <= MAX_FILES:
        raise ValueError(f"max_files must be between 1 and {MAX_FILES:,}.")
    if not 1024 <= max_file_bytes <= MAX_FILE_BYTES:
        raise ValueError(f"max_file_bytes must be between 1,024 and {MAX_FILE_BYTES:,}.")
    if not 1024 <= max_total_bytes <= MAX_TOTAL_BYTES:
        raise ValueError(f"max_total_bytes must be between 1,024 and {MAX_TOTAL_BYTES:,}.")
    if not 200 <= chunk_chars <= 8_000:
        raise ValueError("chunk_chars must be between 200 and 8,000.")
    approved_roots = [resolve_corpus_root(root) for root in roots]
    if not approved_roots:
        raise ValueError("Provide at least one absolute, approved corpus root.")

    records: list[dict[str, str]] = []
    files: list[str] = []
    digest = hashlib.sha256()
    total_bytes = 0
    skipped = 0
    seen: set[Path] = set()
    for root_index, root in enumerate(approved_roots):
        def onerror(error: OSError) -> None:
            raise error
        for current, directory_names, filenames in os.walk(root, topdown=True, followlinks=False, onerror=onerror):
            current_path = Path(current)
            directory_names[:] = sorted(
                name for name in directory_names
                if name.casefold() not in SKIP_DIRECTORIES
                and name.casefold() not in SENSITIVE_DIRECTORY_NAMES
                and not name.startswith(".")
                and not _sensitive_name(name)
                and not (current_path / name).is_symlink()
            )
            for filename in sorted(filenames):
                candidate = current_path / filename
                if candidate.is_symlink() or _is_hidden_or_sensitive(candidate, root):
                    skipped += 1
                    continue
                if candidate.suffix.lower() not in SOURCE_SUFFIXES:
                    skipped += 1
                    continue
                try:
                    resolved = candidate.resolve(strict=True)
                    resolved.relative_to(root)
                    if resolved in seen: continue
                    stat = resolved.stat()
                    if not resolved.is_file() or stat.st_size < 1 or stat.st_size > max_file_bytes:
                        skipped += 1
                        continue
                    raw = resolved.read_bytes()
                    source_text = raw.decode("utf-8")
                except (OSError, UnicodeDecodeError, ValueError):
                    skipped += 1
                    continue
                if b"\x00" in raw or not source_text.strip():
                    skipped += 1
                    continue
                if total_bytes + len(raw) > max_total_bytes:
                    raise ValueError(f"Approved corpus exceeds the {max_total_bytes:,}-byte total source limit.")

                relative = resolved.relative_to(root).as_posix()
                source_id = f"root-{root_index + 1}/{relative}"
                normalized = normalize_source_text(source_text, resolved.suffix)
                if len(normalized) < 24:
                    skipped += 1
                    continue
                if resolved.suffix.lower() == ".json":
                    try:
                        normalized = json.dumps(json.loads(normalized), ensure_ascii=False, indent=2)
                    except json.JSONDecodeError:
                        skipped += 1
                        continue

                seen.add(resolved)
                files.append(source_id)
                total_bytes += len(raw)
                digest.update(source_id.encode("utf-8"))
                digest.update(len(raw).to_bytes(8, "big"))
                digest.update(raw)
                language = _language(resolved)
                for chunk in _split_lines(normalized, chunk_chars):
                    records.append({
                        "prompt": (
                            "### Instruction\n"
                            f"Reproduce this clean {language} source excerpt from the supplied local project. "
                            "Preserve identifiers, imports, syntax, and exact statements. "
                            "Return source only, without Markdown fences.\n\n"
                            f"### Source file\n{relative}\n\n### Response\n"
                        ),
                        "completion": chunk,
                        "source": source_id,
                        "kind": "source-reproduction",
                    })
                    if language in {"Python", "JavaScript", "TypeScript"}:
                        records.append({
                            "prompt": (
                                f"### Instruction\nDescribe only the declarations and import specifiers "
                                f"visible in this {language} excerpt. Do not infer behavior or APIs.\n\n"
                                f"### Source\n{chunk}\n\n### Response\n"
                            ),
                            "completion": _declaration_summary(chunk, language),
                            "source": source_id,
                            "kind": "source-inspection",
                        })
                    if len(records) > MAX_RECORDS:
                        raise ValueError(f"Prepared corpus exceeds the {MAX_RECORDS:,}-record limit.")
    if not records:
        raise ValueError("No clean source examples were found. Check the approved roots and supported file extensions.")
    return PreparedCorpus(records=records, files=files, source_bytes=total_bytes,
                          sha256=digest.hexdigest(), skipped_files=skipped)
